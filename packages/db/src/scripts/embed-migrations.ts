/**
 * Embeds drizzle/*.sql into src/migrations.generated.ts so `migrate()` works inside bundlers
 * (Next.js) where the drizzle/ folder is not on disk next to the compiled code.
 * Run after `drizzle-kit generate`: `pnpm --filter @neighborline/db generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

export function readMigrationsFromDisk(): Array<{ tag: string; sql: string }> {
  const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8')) as {
    entries: Array<{ idx: number; tag: string }>;
  };
  return [...journal.entries]
    .sort((a, b) => a.idx - b.idx)
    .map((e) => ({ tag: e.tag, sql: readFileSync(join(root, 'drizzle', `${e.tag}.sql`), 'utf8') }));
}

export function renderGenerated(migrations: Array<{ tag: string; sql: string }>): string {
  return `// GENERATED by src/scripts/embed-migrations.ts from drizzle/*.sql. Do not edit.
export const MIGRATIONS: ReadonlyArray<{ tag: string; sql: string }> = ${JSON.stringify(migrations, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src/migrations.generated.ts'), renderGenerated(readMigrationsFromDisk()));
  console.log('wrote src/migrations.generated.ts');
}
