/**
 * Keeps `next build` / `next dev` with a custom NEXT_DIST_DIR from rewriting the tracked apps/web/tsconfig.json.
 *
 * Next adds `<distDir>/types/**\/*.ts` to the `include` of the tsconfig it is given whenever that exact string is
 * missing. The tracked tsconfig.json lists `.next/types/**\/*.ts`, so the default build leaves it alone; for any other
 * dist dir we hand Next a generated tsconfig (`.next-tsconfig-<dir>.json`, git-ignored by `.next*`) that extends
 * tsconfig.json and already lists that dist dir's types. Next finds nothing to add and writes nothing.
 *
 * next-env.d.ts is regenerated by Next on every build with the dist dir's route types path, so it is git-ignored
 * (as Next recommends) and next-types.d.ts carries the `next` type references for a fresh checkout.
 *
 * Imported by next.config.ts: plain Node APIs only.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const DEFAULT_DIST_DIR = '.next';

/** `.next-e2e` → `.next-tsconfig-next-e2e.json`; `build/out` → `.next-tsconfig-build-out.json`. */
export function distTsconfigName(distDir: string): string {
  const slug = distDir.replace(/^[./\\]+/, '').replace(/[^A-Za-z0-9_-]+/g, '-').replace(/-+$/, '') || 'dist';
  return `.next-tsconfig-${slug}.json`;
}

interface TsconfigShape {
  include?: string[];
  exclude?: string[];
}

/**
 * The generated tsconfig: extends the tracked one and repeats its `include` and `exclude` (a child's are its own,
 * and Next adds a default `exclude` to a config that has none), plus this dist dir's types.
 */
export function distTsconfigContent(base: TsconfigShape, distDir: string): string {
  const dir = distDir.replace(/\\/g, '/').replace(/\/+$/, '');
  const types = `${dir}/types/**/*.ts`;
  const include = [...(base.include ?? ['**/*.ts', '**/*.tsx']).filter((p) => p !== `${DEFAULT_DIST_DIR}/types/**/*.ts`), types];
  const exclude = base.exclude ?? ['node_modules'];
  // `plugins` repeated so Next doesn't warn that it can't add its TypeScript plugin to an extending config.
  const body = { extends: './tsconfig.json', compilerOptions: { plugins: [{ name: 'next' }] }, include: [...new Set(include)], exclude };
  return `// Generated by next.config.ts for NEXT_DIST_DIR=${distDir}. Git-ignored; edit tsconfig.json instead.\n${JSON.stringify(body, null, 2)}\n`;
}

/**
 * The `typescript.tsconfigPath` for next.config.ts: `tsconfig.json` for the default dist dir, otherwise the generated
 * file, written (only when its content changes) into `projectDir`.
 */
export function distTsconfigPath(projectDir: string, distDir: string): string {
  if (distDir === DEFAULT_DIST_DIR) return 'tsconfig.json';
  const base = JSON.parse(readFileSync(join(projectDir, 'tsconfig.json'), 'utf8')) as TsconfigShape;
  const name = distTsconfigName(distDir);
  const file = join(projectDir, name);
  const content = distTsconfigContent(base, distDir);
  let current: string | undefined;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    current = undefined;
  }
  if (current !== content) writeFileSync(file, content);
  return name;
}
