/**
 * What a real sandbox run feeds back into the repo (sandbox runs only, never the fake):
 *  - the exact duplicate-sender_batch_id error body, as a fixture that packages/paypal's tests check the client's
 *    duplicate detection against (packages/paypal/src/fixtures/duplicate-sender-batch/*.json);
 *  - a generated "Observed in the sandbox" block in packages/paypal/PAYPAL_NOTES.md.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { SpikeData } from '../evidence.js';
import type { DuplicateProbe } from './probes.js';

export const FIXTURE_DIR = 'packages/paypal/src/fixtures/duplicate-sender-batch';

export function writeDuplicateFixture(repo: string, probe: DuplicateProbe, originalBatchId: string, date: string): string | null {
  if (!probe.reused.body || probe.reused.status === undefined) return null;
  const dir = join(repo, FIXTURE_DIR);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, `sandbox-${date}.json`);
  const fixture = {
    source: `PayPal sandbox, ${date} (scripts/golive sandbox-spike)`,
    status: probe.reused.status,
    body: probe.reused.body,
    // The batch the error must resolve to; null when PayPal's body carries no link (createBatch then throws DuplicateBatchError).
    expectBatchId: probe.linkedBatchId ? originalBatchId : null,
  };
  writeFileSync(file, `${JSON.stringify(fixture, null, 2)}\n`);
  return `${FIXTURE_DIR}/sandbox-${date}.json`;
}

const START = '<!-- golive:observed:start -->';
const END = '<!-- golive:observed:end -->';

export function observedBlock(d: SpikeData): string {
  const items = (d.batches ?? []).flatMap((b) => b.items ?? []);
  const dup = d.duplicate;
  const neg = (d.negative ?? []).filter((n) => n.status !== undefined);
  const lines = [
    START,
    `### Observed in the sandbox (${d.startedAt.slice(0, 10)}, run \`${d.runId}\`; generated by \`pnpm golive\`, see docs/SANDBOX_EVIDENCE.md)`,
    '',
    dup
      ? `- **Duplicate \`sender_batch_id\`:** HTTP ${dup.reused.status} \`${dup.reused.name}\`${dup.reused.issue ? `, issue "${dup.reused.issue}"` : ''}; batch link at ${dup.reused.linkPaths.map((p) => `\`${p}\``).join(', ') || 'none'}. Client detection ${dup.detectedAsDuplicate ? 'matches' : 'DOES NOT match'}; the body is pinned in \`${FIXTURE_DIR}/\`.`
      : '- Duplicate `sender_batch_id`: not probed.',
    `- **Item outcomes:** ${items.map((i) => `${i.wallet} ${i.recipientType}${i.receiver.startsWith('@') ? ' (with @)' : ''} → ${i.status}${i.errorName ? ` (${i.errorName})` : ''}`).join('; ') || 'none'}.`,
    d.phone ? `- **PHONE recipient:** ${d.phone.createError ? `refused, HTTP ${d.phone.createError.status} ${d.phone.createError.name}` : `accepted (${d.phone.batchStatus})`}.` : '',
    neg.length ? `- **Negative-testing statuses:** ${neg.map((n) => `${n.code} → ${n.status} ${n.name ?? ''}`.trim()).join(', ')}.` : '',
    d.reconcile ? `- **Transaction Search:** ${d.reconcile.matched.length} of ${items.length} items matched by \`transaction_id\`${d.reconcile.matched.length ? `; lag ${d.reconcile.matched.map((m) => m.lagMinutes).filter((x) => x !== null).join('/') || '?'} min` : ''}; ${d.reconcile.pendingLag.length} pending at ${d.reconcile.checkedAt}${d.reconcile.status === 'pending' && !d.reconcile.matched.length ? ' (PayPal\'s reporting not ready yet for a new account)' : ''}.` : '',
    END,
  ].filter((l) => l !== '');
  return lines.join('\n');
}

/** Insert or replace the generated block, right after the "To verify in the real sandbox" list. */
export function spliceObserved(notes: string, block: string): string {
  if (notes.includes(START) && notes.includes(END)) return notes.slice(0, notes.indexOf(START)) + block + notes.slice(notes.indexOf(END) + END.length);
  const anchor = notes.search(/^## To verify in the real sandbox.*$/m);
  if (anchor === -1) return `${notes.trimEnd()}\n\n${block}\n`;
  const nextHeading = notes.slice(anchor + 1).search(/^## /m);
  const at = nextHeading === -1 ? notes.length : anchor + 1 + nextHeading;
  return `${notes.slice(0, at).trimEnd()}\n\n${block}\n\n${notes.slice(at)}`;
}

export function updatePaypalNotes(repo: string, d: SpikeData): string | null {
  const file = join(repo, 'packages/paypal/PAYPAL_NOTES.md');
  if (!existsSync(file)) return null;
  writeFileSync(file, spliceObserved(readFileSync(file, 'utf8'), observedBlock(d)));
  return 'packages/paypal/PAYPAL_NOTES.md';
}
