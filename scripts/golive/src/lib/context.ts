/** What every step gets, and what it returns. */
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDotenv, redactSecrets, type Env } from './env.js';
import type { Runner } from './proc.js';

export const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');

export type StepStatus = 'ok' | 'skipped' | 'pending' | 'warn' | 'failed';

export interface StepResult {
  status: StepStatus;
  /** One line for the summary table. */
  summary: string;
  /** What the human (or the next run) should do now. Required for failed/pending/skipped. */
  next?: string;
  /** Files this step wrote, relative to the repo. */
  outputs?: string[];
}

export interface Ctx {
  repo: string;
  /** golive-out/ (git-ignored). */
  out: string;
  env: Env;
  dryRun: boolean;
  /** Redo parts that already succeeded. */
  force: boolean;
  state: StateStore;
  run: Runner;
  fetch: typeof fetch;
  now: () => Date;
  sleep: (ms: number) => Promise<void>;
  log: (msg: string) => void;
  /** Set a generated env value: written to golive-out/golive.env and visible to later steps. */
  setGenerated: (key: string, value: string) => void;
}

export interface Step {
  name: string;
  title: string;
  run: (ctx: Ctx) => Promise<StepResult>;
}

/** golive-out/state.json: per-step results and resumable per-part data. */
export class StateStore {
  private data: { steps: Record<string, { status: StepStatus; summary: string; at: string; next?: string }>; parts: Record<string, Record<string, unknown>> };

  constructor(private readonly file: string) {
    this.data = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : { steps: {}, parts: {} };
    this.data.steps ??= {};
    this.data.parts ??= {};
  }

  step(name: string) {
    return this.data.steps[name];
  }

  setStep(name: string, r: StepResult, at: Date): void {
    this.data.steps[name] = { status: r.status, summary: r.summary, at: at.toISOString(), ...(r.next ? { next: r.next } : {}) };
    this.save();
  }

  /** Per-step scratch data (ids created, parts done) that makes a re-run resume instead of redo. */
  get<T = Record<string, unknown>>(step: string): T {
    return (this.data.parts[step] ??= {}) as T;
  }

  patch(step: string, value: Record<string, unknown>): void {
    this.data.parts[step] = { ...(this.data.parts[step] ?? {}), ...value };
    this.save();
  }

  reset(step: string): void {
    delete this.data.parts[step];
    this.save();
  }

  save(): void {
    mkdirSync(dirname(this.file), { recursive: true });
    writeFileSync(this.file, `${JSON.stringify(this.data, null, 2)}\n`);
  }
}

export function writeOut(ctx: Pick<Ctx, 'out'>, name: string, content: string | object): string {
  const file = join(ctx.out, name);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, typeof content === 'string' ? content : `${JSON.stringify(content, null, 2)}\n`);
  return file;
}

/** Upsert KEY=value in golive-out/golive.env (kept sorted, one per line). */
export function upsertGeneratedEnv(file: string, key: string, value: string): void {
  const cur = existsSync(file) ? parseDotenv(readFileSync(file, 'utf8')) : {};
  cur[key] = value;
  mkdirSync(dirname(file), { recursive: true });
  const body = Object.keys(cur)
    .sort()
    .map((k) => `${k}=${cur[k]}`)
    .join('\n');
  writeFileSync(file, `# Generated by pnpm golive. Paste into Render / .env as needed; golive reads it back on the next run.\n${body}\n`);
}

/** A logger that writes to the console and golive-out/golive.log, with secrets masked. */
export function makeLogger(out: string, env: () => Env, quiet = false): (msg: string) => void {
  const file = join(out, 'golive.log');
  return (msg: string) => {
    const safe = redactSecrets(msg, env());
    if (!quiet) console.log(safe);
    try {
      mkdirSync(out, { recursive: true });
      appendFileSync(file, `${new Date().toISOString()} ${safe}\n`);
    } catch {
      /* logging must never fail a step */
    }
  };
}

export const rel = (ctx: Pick<Ctx, 'repo'>, file: string) => (file.startsWith(ctx.repo) ? file.slice(ctx.repo.length + 1) : file);
